-- Audit Manifest Table
CREATE TABLE IF NOT EXISTS bronze.load_manifest (
    load_id BIGSERIAL PRIMARY KEY,
    file_name TEXT NOT NULL,
    file_path TEXT NOT NULL,
    file_size_bytes BIGINT,
    file_sha256 TEXT NOT NULL,
    target_table TEXT NOT NULL,
    row_count BIGINT NOT NULL,
    status TEXT NOT NULL,
    loaded_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    execution_time_seconds NUMERIC(10, 4),
    error_message TEXT
);

CREATE INDEX IF NOT EXISTS idx_load_manifest_hash ON bronze.load_manifest (file_sha256);
CREATE INDEX IF NOT EXISTS idx_load_manifest_file ON bronze.load_manifest (file_name);

