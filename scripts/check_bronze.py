"""
scripts/check_bronze.py
Validates landed PostgreSQL Bronze tables:
  - Exact row count reconciliation against source specs.
  - Audit column verification (_row_id, _loaded_at, _source_file).
  - Load manifest integrity.
  - Outputs docs/bronze/bronze_profile.md.
"""

import os
import sys
import psycopg

POSTGRES_HOST = os.getenv("POSTGRES_HOST", "postgres")
POSTGRES_PORT = os.getenv("POSTGRES_PORT", "5432")
POSTGRES_DB   = os.getenv("POSTGRES_DB", "dwh")
POSTGRES_USER = os.getenv("POSTGRES_USER", "pharma_admin")
POSTGRES_PASSWORD = os.getenv("POSTGRES_PASSWORD", "pharma_secret_pw")

CONN_STR = f"host={POSTGRES_HOST} port={POSTGRES_PORT} dbname={POSTGRES_DB} user={POSTGRES_USER} password={POSTGRES_PASSWORD}"

EXPECTED_COUNTS = {
    "bronze.master_data": 63,
    "bronze.manufacturing_data": 561,
    "bronze.manufacturer_delivery_data": 999,
    "bronze.warehouse_data": 112184,
    "bronze.pharmacy_sales_data": 500000,
    "bronze.hospital_demand_data": 27216,
    "bronze.iot_streaming_data": 293425
}

def main():
    print("=" * 80)
    print("VALIDATING POSTGRESQL BRONZE LAYER")
    print("=" * 80)

    conn = psycopg.connect(CONN_STR)
    cur = conn.cursor()

    report_lines = [
        "# Bronze Layer Audit and Reconciliation Report",
        "Generated by `scripts/check_bronze.py`.\n",
        "| Table Name | Expected Rows | Actual Landed Rows | Delta | Audit Columns | Manifest Check | Status |",
        "|---|---|---|---|---|---|---|"
    ]

    all_passed = True

    for tbl, expected in EXPECTED_COUNTS.items():
        # Check row count
        cur.execute(f"SELECT COUNT(*) FROM {tbl};")
        actual = cur.fetchone()[0]
        delta = actual - expected

        # Check audit columns
        cur.execute(f"""
            SELECT COUNT(*) 
            FROM {tbl} 
            WHERE _row_id IS NULL OR _loaded_at IS NULL OR _source_file IS NULL;
        """)
        null_audit = cur.fetchone()[0]
        audit_ok = "PASS (0 NULLs)" if null_audit == 0 else f"FAIL ({null_audit} NULLs)"

        # Check manifest
        cur.execute(f"""
            SELECT COUNT(*) 
            FROM bronze.load_manifest 
            WHERE target_table = '{tbl}' AND status = 'SUCCESS';
        """)
        manifest_cnt = cur.fetchone()[0]
        manifest_ok = f"PASS ({manifest_cnt} run)" if manifest_cnt > 0 else "FAIL (Missing)"

        passed = (delta == 0 and null_audit == 0 and manifest_cnt > 0)
        status_str = "**PASS**" if passed else "**FAIL**"
        if not passed:
            all_passed = False

        print(f"  {tbl:35s}: Landed {actual:,} (Expected: {expected:,}) | Audit: {audit_ok} | Status: {status_str}")
        report_lines.append(f"| `{tbl}` | {expected:,} | {actual:,} | {delta:+d} | {audit_ok} | {manifest_ok} | {status_str} |")

    os.makedirs("/workspace/docs/bronze", exist_ok=True)
    with open("/workspace/docs/bronze/bronze_profile.md", "w", encoding="utf-8") as f:
        f.write("\n".join(report_lines) + "\n")

    print("\nSaved report to docs/bronze/bronze_profile.md")
    
    conn.close()
    if all_passed:
        print("\nSUCCESS: All Bronze tables reconciled 100% to source specifications.")
    else:
        print("\nERROR: Discrepancy detected in Bronze validation!")
        sys.exit(1)

if __name__ == "__main__":
    main()
